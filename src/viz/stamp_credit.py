"""Stamp the credit onto existing PNG figures that cannot be regenerated right now (e.g. stages whose raw inputs sit on
an unavailable OneDrive). Adds a white strip at the bottom with 'Visualisation: Charles Gava' (bold, right-aligned)
and records a PNG text chunk ('credit') so a file is never stamped twice. Figures regenerated by the pipelines carry
the credit natively and are skipped when they are newer than --since.

Usage: python -m src.viz.stamp_credit <dir> [<dir> ...] [--since YYYY-MM-DDTHH:MM] [--org "Hove & Quill"] [--check]
"""
import datetime as dt
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, PngImagePlugin

from src.viz.credit import AUTHOR

FONT = "/System/Library/Fonts/Supplemental/Times New Roman Bold.ttf"


def stamped(img):
    return "credit" in (img.info or {})


def stamp(path, org=None):
    img = Image.open(path)
    if stamped(img):
        return False
    img = img.convert("RGB")
    w, h = img.size
    size = max(14, int(h * 0.022))
    strip = int(size * 1.9)
    out = Image.new("RGB", (w, h + strip), "white")
    out.paste(img, (0, 0))
    text = f"Visualisation: {AUTHOR}" + (f", {org}" if org else "")
    d = ImageDraw.Draw(out)
    font = ImageFont.truetype(FONT, size)
    tw = d.textlength(text, font=font)
    d.text((w - tw - int(size * 0.8), h + (strip - size) // 2 - 2), text, fill=(63, 61, 57), font=font)
    meta = PngImagePlugin.PngInfo()
    meta.add_text("credit", text)
    dpi = img.info.get("dpi", (300, 300))
    out.save(path, pnginfo=meta, dpi=dpi)
    return True


def main(argv):
    dirs, skip = [], False
    for a in argv:
        if skip:
            skip = False
        elif a in ("--since", "--org"):
            skip = True
        elif not a.startswith("--"):
            dirs.append(Path(a))
    since = dt.datetime.fromisoformat(argv[argv.index("--since") + 1]).timestamp() if "--since" in argv else None
    org = argv[argv.index("--org") + 1] if "--org" in argv else None
    check = "--check" in argv
    n_stamp = n_skip = 0
    for d in dirs:
        for p in sorted(d.rglob("*.png")):
            if since and p.stat().st_mtime >= since:
                n_skip += 1                         # regenerated after the credit was added: credit is native
                continue
            if check:
                print(("stamped " if stamped(Image.open(p)) else "MISSING ") + str(p))
                continue
            if stamp(p, org):
                n_stamp += 1
                print(f"stamped {p}")
    print(f"{n_stamp} stamped, {n_skip} already carry the credit natively")


if __name__ == "__main__":
    main(sys.argv[1:])
